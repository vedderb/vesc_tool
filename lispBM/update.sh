#!/bin/bash
# Copies the parts of LispBM that the Virtual ESC builds into lispBM/ and the color extensions of the Express
# into express/, and regenerates lbm_rename.h. Takes a LispBM branch, tag or commit, master by default.
# Needs git, a C compiler and nm. On Windows run it in Git Bash with a compiler in the PATH, such as the
# MinGW of Qt (C:/Qt/Tools/mingw*/bin). Commit the result after checking it with git status.
set -e
cd "$(dirname "$0")"
ref=${1:-master}
keep="LICENSE README.md include src utils platform/qt5 repl/vesc_extension_stubs.c repl/vesc_mock.h"

# A relative folder, which Git Bash and native Windows compilers see the same
tmp=.update_tmp
rm -rf $tmp
trap 'rm -rf $tmp' EXIT

git init -q $tmp/lispbm
git -C $tmp/lispbm fetch -q --depth 1 https://github.com/svenssonjoel/lispBM.git "$ref"
git -C $tmp/lispbm checkout -q FETCH_HEAD
rm -rf lispBM
for p in $keep; do
    mkdir -p "lispBM/$(dirname "$p")"
    cp -R "$tmp/lispbm/$p" "lispBM/$p"
done

# The color extensions of the Express, with shims for its headers in express/
git clone -q --depth 1 https://github.com/vedderb/vesc_express.git $tmp/express
cp $tmp/express/main/lbm_color_extensions.c express/

{
    echo "lispBM/ has the parts of https://github.com/svenssonjoel/lispBM that the Virtual ESC builds, commit $(git -C $tmp/lispbm log -1 --format='%h (%cs)')."
    echo "express/lbm_color_extensions.c from https://github.com/vedderb/vesc_express, commit $(git -C $tmp/express log -1 --format='%h (%cs)')."
    echo
    echo "Run update.sh to update them. vl_node.c is the Virtual ESC runtime, compiled once per simulated device."
} > README.md

# Every runtime is a separate copy with prefixed symbols, see vl_node.c
cc=${CC:-$(command -v cc || command -v gcc || true)}
[ -n "$cc" ] || { echo "No C compiler found, set CC"; exit 1; }
L=lispBM
"$cc" -c -std=gnu11 -w -I. -I$L/include -I$L/include/extensions -I$L/src/extensions -I$L/utils \
    -I$L/platform/qt5/include -I$L/repl -DVL_PFX=vl -DVL_NO_RENAME vl_node.c -o $tmp/node.o
${NM:-nm} -g --defined-only $tmp/node.o | awk '{print $3}' | sed 's/^_//' | grep -v '^vl_api$' |
    awk 'BEGIN {print "// Generated by update.sh"} {print "#define " $1 " VL_NAME(" $1 ")"}' > lbm_rename.h
