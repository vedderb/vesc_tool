#!/bin/bash
# Pulls the latest LispBM into the lispBM/ subtree, copies the color extensions
# of the Express and regenerates lbm_rename.h. Run from a clean working tree,
# it commits the update.
set -e
cd "$(dirname "$0")"
old=$(git rev-parse HEAD)
git -C "$(git rev-parse --show-toplevel)" subtree pull --prefix=lispBM/lispBM https://github.com/svenssonjoel/lispBM.git master --squash \
    -m "Update LispBM subtree"

# The color extensions of the Express, with shims for its headers in express/
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
git clone -q --depth 1 https://github.com/vedderb/vesc_express.git "$tmp/express"
cp "$tmp/express/main/lbm_color_extensions.c" express/
{
    echo "LispBM is a git subtree of https://github.com/svenssonjoel/lispBM in lispBM/."
    echo "express/lbm_color_extensions.c from https://github.com/vedderb/vesc_express, commit $(git -C "$tmp/express" log -1 --format='%h (%cs)')."
    echo
    echo "Run update.sh to update them. vl_node.c is the Virtual ESC runtime, compiled once per simulated device."
} > README.md

# Every runtime is a separate copy with prefixed symbols, see vl_node.c
L=lispBM
cc -c -std=gnu11 -w -I. -I$L/include -I$L/include/extensions -I$L/src/extensions -I$L/utils \
    -I$L/platform/qt5/include -I$L/repl -DVL_PFX=vl -DVL_NO_RENAME vl_node.c -o "$tmp/node.o"
nm -g --defined-only "$tmp/node.o" | awk '{print $3}' | sed 's/^_//' | grep -v '^vl_api$' |
    awk 'BEGIN {print "// Generated by update.sh"} {print "#define " $1 " VL_NAME(" $1 ")"}' > lbm_rename.h

# Into the subtree merge commit, so that every commit links
if [ "$(git rev-parse HEAD)" != "$old" ]; then
    git add lbm_rename.h README.md express/lbm_color_extensions.c
    git commit --amend --no-edit -q
fi
