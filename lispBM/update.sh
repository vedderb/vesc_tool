#!/bin/bash
# Copies the latest LispBM from upstream and regenerates lbm_rename.h.
set -e
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

git clone -q --depth 1 https://github.com/svenssonjoel/lispBM.git "$tmp/lbm"
rm -rf include src utils repl platform
cp -r "$tmp/lbm/include" "$tmp/lbm/src" "$tmp/lbm/LICENSE" .
mkdir -p utils repl platform
cp "$tmp"/lbm/utils/{tinygfx.c,tinygfx.h,tinygfx_fonts.h,tjpgd.c,tjpgd.h,tjpgdcnf.h,buffer.c,buffer.h,cos_table.h,tinyutils.h} utils/
cp "$tmp"/lbm/repl/{vesc_extension_stubs.c,vesc_extension_stubs.h,vesc_mock.h} repl/
cp "$tmp"/lbm/platform/qt5/include/*.h "$tmp"/lbm/platform/qt5/src/platform_mutex.cpp platform/

# The color extensions of the Express, with shims for its headers in express/
git clone -q --depth 1 https://github.com/vedderb/vesc_express.git "$tmp/express"
cp "$tmp/express/main/lbm_color_extensions.c" express/
{
    echo "LispBM from https://github.com/svenssonjoel/lispBM, commit $(git -C "$tmp/lbm" log -1 --format='%h (%cs)')."
    echo "express/lbm_color_extensions.c from https://github.com/vedderb/vesc_express, commit $(git -C "$tmp/express" log -1 --format='%h (%cs)')."
    echo
    echo "Run update.sh to update them. vl_node.c is the Virtual ESC runtime, compiled once per simulated device."
} > README.md

# Every runtime is a separate copy with prefixed symbols, see vl_node.c
cc -c -std=gnu11 -w -I. -Iinclude -Iinclude/extensions -Isrc/extensions -Iutils -Iplatform -Irepl -DVL_PFX=vl -DVL_NO_RENAME vl_node.c -o "$tmp/node.o"
nm -g --defined-only "$tmp/node.o" | awk '{print $3}' | sed 's/^_//' | grep -v '^vl_api$' |
    awk 'BEGIN {print "// Generated by update.sh"} {print "#define " $1 " VL_NAME(" $1 ")"}' > lbm_rename.h
